"""
Decodes, with the reference HeartCodec, frames generated by the .NET version
(a reference for listening comparisons; the C# codec is `generate --wav`). If this sounds like music, the LLM in .NET works.

    python decode_frames.py --model_path ./ckpt --frames frames.safetensors --out out.wav
"""
import argparse

import torch
import torchaudio
from safetensors.torch import load_file

from heartlib.heartcodec.modeling_heartcodec import HeartCodec


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model_path", required=True)
    ap.add_argument("--frames", default="frames.safetensors")
    ap.add_argument("--out", default="out.wav")
    ap.add_argument("--device", default="cuda")
    args = ap.parse_args()

    frames = load_file(args.frames)["frames"].to(args.device)  # [K, T]
    codec = HeartCodec.from_pretrained(f"{args.model_path}/HeartCodec-oss", device_map=args.device, dtype=torch.float32)
    wav = codec.detokenize(frames)
    torchaudio.save(args.out, wav.to(torch.float32).cpu(), 48000)
    print(f"saved {args.out}")


if __name__ == "__main__":
    main()
