using MusicGen.Core.Testing;
using HeartMuLa.Model;
using TorchSharp;
using Xunit.Abstractions;
using static TorchSharp.torch;

namespace HeartMuLa.Tests;

/// <summary>
/// Parity of the C# HeartMuLa forward pass against the Python golden run (tests/fixtures, see MANIFEST.md),
/// with HeartMuLa-oss-3B in bf16. The model is shared by the whole RealModel collection.
/// </summary>
[Collection(RealModelCollection.Name)]
public sealed class ModelParityTests
{
    private readonly RealModelFixture _fx;
    private readonly ITestOutputHelper _out;

    public ModelParityTests(RealModelFixture fx, ITestOutputHelper output) { _fx = fx; _out = output; }

    private static void AssertWithin(string what, Parity.Result r, bool isLogits)
    {
        Assert.True(r.CosSim >= Parity.MinCosSim, $"{what}: cos_sim {r.CosSim:F6} < {Parity.MinCosSim}");
        if (isLogits)
            Assert.True(r.MaxAbs <= Parity.MaxAbsLogits, $"{what}: max_abs {r.MaxAbs:E3} > {Parity.MaxAbsLogits}");
    }

    [RequiresCheckpoint]
    public void Backbone_FirstFrame_MatchesPython()
    {
        var model = _fx.ModelWithFreshCaches();
        var r = Fixtures.Load("reference.safetensors");
        using var _ = no_grad();

        var tokens = r["tokens"].to(_fx.Device);
        var mask = r["tokens_mask"].to(_fx.Device);
        var pos = r["pos"].to(_fx.Device);
        var muq = r["muq_embed"].to(ScalarType.BFloat16).to(_fx.Device);
        int muqIdx = (int)r["muq_idx"].item<long>();
        int bs = (int)tokens.shape[0];
        Assert.Equal(2, bs);

        var (lastH, c0) = model.BackboneLogits(tokens, mask, pos, (double)r["cfg_scale"].item<float>(), muq, Enumerable.Repeat(muqIdx, bs).ToArray());

        Assert.Equal(r["last_h"].shape, lastH.shape);
        Assert.Equal(r["c0_logits"].shape, c0.shape);
        var h = Parity.Compare(lastH, r["last_h"]);
        var l = Parity.Compare(c0, r["c0_logits"]);
        _out.WriteLine($"last_h    {h}");
        _out.WriteLine($"c0_logits {l}");
        AssertWithin("last_h", h, isLogits: false);
        AssertWithin("c0_logits", l, isLogits: true);
    }

    /// <summary>
    /// Teacher forcing: call 0 is the prompt and call t ≥ 1 receives frame t-1 generated by Python
    /// (in both CFG rows), with the KV cache accumulating. Each call is compared with frames_logits.safetensors
    /// (raw, before CFG): row 0 = conditional, row 1 = unconditional.
    /// </summary>
    [RequiresCheckpoint]
    public void Backbone_TeacherForcing_MatchesPythonOnAll126Calls()
    {
        var model = _fx.ModelWithFreshCaches();
        var r = Fixtures.Load("reference.safetensors");
        var frames = Fixtures.Load("frames_py.safetensors")["frames"];       // [8, T]
        var expected = Fixtures.Load("frames_logits.safetensors");
        var expLogits = expected["c0_logits"];                               // [calls, 2, V]
        var expLastH = expected["last_h"];                                   // [calls, 2, D]
        long calls = expLogits.shape[0];
        Assert.Equal(126, calls);
        Assert.Equal(calls, frames.shape[1]);                                // call t produces frame t
        using var _ = no_grad();

        var promptPos = r["pos"].to(_fx.Device);
        var cfg = (double)r["cfg_scale"].item<float>();
        int muqIdx = (int)r["muq_idx"].item<long>();

        var results = new List<(int call, int row, Parity.Result lastH, Parity.Result logits)>();
        for (int t = 0; t < calls; t++)
        {
            Tensor lastH, logits;
            if (t == 0)
            {
                (lastH, logits) = model.BackboneLogits(
                    r["tokens"].to(_fx.Device), r["tokens_mask"].to(_fx.Device), promptPos, cfg,
                    r["muq_embed"].to(ScalarType.BFloat16).to(_fx.Device), new[] { muqIdx, muqIdx });
            }
            else
            {
                var frame = frames[.., (t - 1)..t].reshape(1, 8).repeat(2, 1).to(_fx.Device);  // frame t-1 in both rows
                var (tokens, mask) = Pipeline.MusicGenerationPipeline.PadAudioToken(frame, emptyId: 0);
                var pos = promptPos[.., ^1..] + t;
                (lastH, logits) = model.BackboneLogits(tokens, mask, pos, cfg);
            }

            for (int row = 0; row < 2; row++)
                results.Add((t, row,
                    Parity.Compare(lastH[row], expLastH[t, row]),
                    Parity.Compare(logits[row], expLogits[t, row])));
            lastH.Dispose();
            logits.Dispose();
        }

        string Worst(IEnumerable<(int call, int row, Parity.Result lastH, Parity.Result logits)> rs, Func<(int call, int row, Parity.Result lastH, Parity.Result logits), Parity.Result> pick, bool byCos)
        {
            var w = byCos ? rs.MinBy(x => pick(x).CosSim) : rs.MaxBy(x => pick(x).MaxAbs);
            return $"call {w.call} row {w.row}: {pick(w)}";
        }

        var first = results.Where(x => x.call < 26).ToList();
        var last = results.Where(x => x.call >= calls - 26).ToList();
        _out.WriteLine($"worst cos_sim logits   (all):    {Worst(results, x => x.logits, true)}");
        _out.WriteLine($"worst max_abs logits   (all):    {Worst(results, x => x.logits, false)}");
        _out.WriteLine($"worst cos_sim last_h   (all):    {Worst(results, x => x.lastH, true)}");
        _out.WriteLine($"worst cos_sim logits   (first 26): {Worst(first, x => x.logits, true)}");
        _out.WriteLine($"worst cos_sim logits   (last 26):  {Worst(last, x => x.logits, true)}");
        _out.WriteLine($"worst max_abs logits   (first 26): {Worst(first, x => x.logits, false)}");
        _out.WriteLine($"worst max_abs logits   (last 26):  {Worst(last, x => x.logits, false)}");

        foreach (var (call, row, h, l) in results)
        {
            AssertWithin($"call {call} row {row} last_h", h, isLogits: false);
            AssertWithin($"call {call} row {row} c0_logits", l, isLogits: true);
        }
        // No drift: the last 26 calls meet exactly the same tolerance as the first ones.
        Assert.True(last.Min(x => x.logits.CosSim) >= Parity.MinCosSim && last.Max(x => x.logits.MaxAbs) <= Parity.MaxAbsLogits,
            "the last 26 calls fall outside the tolerance");
    }

    /// <summary>
    /// Decoder (codebooks 1..7) with forced tokens against decoder_logits.safetensors: input = the last_h and the tokens the
    /// heartlib decoder received, so the result does not depend on the backbone. Raw logits, before CFG.
    /// </summary>
    [RequiresCheckpoint]
    public void Decoder_TeacherForced_MatchesPython()
    {
        var model = _fx.ModelWithFreshCaches();
        var d = Fixtures.Load("decoder_logits.safetensors");
        var frameIdx = d["frame_idx"].data<long>().ToArray();
        var lastH = d["last_h"];      // [n, 2, D] float32 (exact bf16 values)
        var tokens = d["tokens"];     // [n, K]
        var expected = d["ci_logits"]; // [n, 2, K-1, V]
        long k = tokens.shape[1];
        Assert.Equal(6, frameIdx.Length);
        using var _ = no_grad();

        var worst = new Parity.Result[k - 1];
        for (int c = 0; c < worst.Length; c++) worst[c] = new Parity.Result(1.0, 0.0);
        var failures = new List<string>();

        for (int j = 0; j < frameIdx.Length; j++)
        {
            var h = lastH[j].to(ScalarType.BFloat16).to(_fx.Device);                       // [2, D]
            var tk = tokens[j].reshape(1, k).repeat(2, 1).to(_fx.Device);                  // [2, K]
            using var logits = model.DecoderLogits(h, tk);                                 // [2, K-1, V]
            Assert.Equal(expected[j].shape, logits.shape);

            for (int row = 0; row < 2; row++)
                for (int c = 0; c < k - 1; c++)
                {
                    var r = Parity.Compare(logits[row, c], expected[j, row, c]);
                    worst[c] = new Parity.Result(Math.Min(worst[c].CosSim, r.CosSim), Math.Max(worst[c].MaxAbs, r.MaxAbs));
                    if (r.CosSim < Parity.MinCosSim || r.MaxAbs > Parity.MaxAbsLogits)
                        failures.Add($"frame {frameIdx[j]} row {row} codebook {c + 1}: {r}");
                }
        }

        for (int c = 0; c < worst.Length; c++)
            _out.WriteLine($"codebook {c + 1}: worst cos_sim={worst[c].CosSim:F6} worst max_abs={worst[c].MaxAbs:E3}");
        Assert.True(failures.Count == 0, "outside tolerance:\n  " + string.Join("\n  ", failures));
    }
}
